#!/usr/bin/env node
// Generates src/shared/emoji-data.ts from iamcal's emoji-data (the source of Slack's shortcodes).
//
//   npm i -D emoji-datasource   # bump this to pick up new emoji
//   node scripts/gen-emoji.mjs
//
// Output is compact on purpose: it ships to the browser and to the Cloudflare Worker.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkgDir = join(root, 'node_modules/emoji-datasource')
const out = join(root, 'src/shared/emoji-data.ts')

const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
/** @type {any[]} */
const data = JSON.parse(readFileSync(join(pkgDir, 'emoji.json'), 'utf8'))

/** Slack-style picker categories, in display order. Source categories not listed (Component) are skipped. */
const CATEGORIES = [
  { id: 'people', name: 'Smileys & People', icon: '😀', from: ['Smileys & Emotion', 'People & Body'] },
  { id: 'nature', name: 'Nature', icon: '🐻', from: ['Animals & Nature'] },
  { id: 'food', name: 'Food & Drink', icon: '🍔', from: ['Food & Drink'] },
  { id: 'activity', name: 'Activities', icon: '⚽', from: ['Activities'] },
  { id: 'travel', name: 'Travel & Places', icon: '🚗', from: ['Travel & Places'] },
  { id: 'objects', name: 'Objects', icon: '💡', from: ['Objects'] },
  { id: 'symbols', name: 'Symbols', icon: '💕', from: ['Symbols'] },
  { id: 'flags', name: 'Flags', icon: '🏁', from: ['Flags'] },
]
const catOf = new Map(CATEGORIES.flatMap((c) => c.from.map((f) => [f, c])))

const STOP = new Set(['a', 'an', 'and', 'of', 'the', 'with', 'for', 'other'])
const glyphOf = (unified) => String.fromCodePoint(...unified.split('-').map((h) => parseInt(h, 16)))
const words = (s) => s.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w && !STOP.has(w))

/** Keywords from the Unicode name, minus words the short names already contain (search is substring-based). */
function keywords(e) {
  const names = e.short_names.join(' ')
  const seen = new Set()
  return words(e.name).filter((w) => !names.includes(w) && !seen.has(w) && seen.add(w)).join(' ')
}

/** One emoji as a compact tuple; trailing empty fields are dropped. */
function row(e, withKeywords = true) {
  const r = [e.short_name, glyphOf(e.unified), e.short_names.filter((n) => n !== e.short_name).join(' ')]
  if (withKeywords) r.push(keywords(e))
  while (r.length > 2 && !r[r.length - 1]) r.pop()
  return r
}

const q = (s) => {
  if (/['\\\n]/.test(s)) throw new Error(`unexpected character in ${JSON.stringify(s)}`)
  return `'${s}'`
}
const tuple = (r) => `[${r.map(q).join(',')}]`

const sorted = [...data].sort((a, b) => a.sort_order - b.sort_order)
const legacy = sorted.filter((e) => e.obsoleted_by && e.category !== 'Component')
const current = sorted.filter((e) => !e.obsoleted_by)

let total = 0
const blocks = CATEGORIES.map((cat) => {
  // Subcategories keep sort order; their words are stored once per group and added to each item's search text.
  const groups = []
  for (const e of current) {
    if (catOf.get(e.category) !== cat) continue
    const sub = words(e.subcategory).join(' ')
    if (groups.at(-1)?.sub !== sub) groups.push({ sub, rows: [] })
    groups.at(-1).rows.push(row(e))
    total++
  }
  const body = groups.map((g) => `[${q(g.sub)},[\n${g.rows.map((r) => `${tuple(r)},`).join('\n')}\n]],`).join('\n')
  return `[${q(cat.id)},${q(cat.name)},${q(cat.icon)},[\n${body}\n]],`
})

const skipped = new Set(data.map((e) => e.category).filter((c) => !catOf.has(c)))

const src = `// GENERATED by scripts/gen-emoji.mjs from emoji-datasource@${version}. Do not edit by hand.
// Regenerate: npm i -D emoji-datasource@latest && node scripts/gen-emoji.mjs
// Shared by the web app and the Worker: keep it plain data with no imports.

/** [short_name, glyph, aliases (space separated), keywords (space separated)] */
export type EmojiRow = [name: string, glyph: string, aliases?: string, keywords?: string]

/** [subcategory keywords, rows] */
export type EmojiGroup = [subcategory: string, rows: EmojiRow[]]

/** [id, display name, icon glyph, groups] */
export type EmojiCategoryData = [id: string, name: string, icon: string, groups: EmojiGroup[]]

export const EMOJI_DATA_VERSION = '${version}'

/** ${total} standard emoji in Slack picker order. Skipped source categories: ${[...skipped].join(', ') || 'none'}. */
export const EMOJI_DATA: EmojiCategoryData[] = [
${blocks.join('\n')}
]

/** Older shortcodes Slack still accepts (e.g. :runner:), resolvable but not shown in the picker. */
export const EMOJI_LEGACY: EmojiRow[] = [
${legacy.map((e) => `${tuple(row(e, false))},`).join('\n')}
]
`

writeFileSync(out, src)
console.log(`wrote ${out.replace(root + '/', '')}: ${total} emoji + ${legacy.length} legacy, ${Buffer.byteLength(src)} bytes`)
